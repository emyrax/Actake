export type GeoDropTokenSymbol = 'SKR' | 'USDC';
export type GeoDropRadiusMeters = 15 | 25 | 50;

export type GeoDropArAssetKind =
  | 'chest'
  | 'image_depth'
  | 'ai_3d_sculpture'
  | 'custom_glb';

export type GeoDropImageFrameStyle = 'card' | 'medallion' | 'cutout';

export type GeoDropAiPrimitiveShape =
  | 'box'
  | 'cylinder'
  | 'sphere'
  | 'torus'
  | 'cone'
  | 'capsule'
  | 'dodecahedron';

export interface GeoDropAi3DPart {
  shape: GeoDropAiPrimitiveShape;
  position: [number, number, number];
  rotation: [number, number, number];
  scale: [number, number, number];
  colorHex: string;
  metalness: number;
  roughness: number;
  emissiveHex?: string;
  emissiveIntensity?: number;
}

export interface GeoDropAi3DBlueprint {
  title: string;
  summary: string;
  finish: 'metallic' | 'glossy' | 'matte' | 'neon_glass';
  primaryColorHex: string;
  accentColorHex: string;
  glowColorHex: string;
  parts: GeoDropAi3DPart[];
}

export interface GeoDropArAsset {
  kind: GeoDropArAssetKind;
  brandName?: string;
  /** Compressed PNG/JPEG/WebP data URL used for 3D depth relief or AI sculpture emblem */
  imageDataUrl?: string;
  /** Real-time 3D relief extrusion & displacement strength (0.15 - 1.0) */
  depthStrength?: number;
  /** 3D depth silhouette casing shape */
  frameStyle?: GeoDropImageFrameStyle;
  /** Primary brand accent hex color for halo ring and unlock coin burst */
  accentHex?: string;
  /** Structured multi-part 3D blueprint generated by server-side Gemini Vision */
  aiBlueprint?: GeoDropAi3DBlueprint | null;
  /** Safe same-origin URL serving an uploaded validated .glb binary model */
  modelAssetUrl?: string;
  modelFileName?: string;
  modelSizeBytes?: number;
}

